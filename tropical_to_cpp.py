def _terms_to_tokens(terms) -> list:
    """Render a list of sympy terms as latex strings with leading +/- signs."""
    tokens = []
    for i, t in enumerate(terms):
        r = latex(t)
        if i == 0:
            tokens.append(r)
        elif t.could_extract_minus_sign():
            tokens.append(r)        # latex() already gives leading '-'
        else:
            tokens.append("+" + r)
    return tokens


def _factor_to_latex(factor, terms_per_line: int) -> str:
    """
    Render a single sympy factor.  If it is a sum with more than
    terms_per_line summands, wrap it in \\left(…\\right) and insert
    line breaks inside; otherwise just return latex(factor).
    """
    terms = factor.as_ordered_terms()
    if len(terms) <= terms_per_line:
        return latex(factor)

    tokens = _terms_to_tokens(terms)
    lines = []
    for i in range(0, len(tokens), terms_per_line):
        chunk = tokens[i : i + terms_per_line]
        lines.append("    " + " ".join(chunk))

    inner = " \\\\\n".join(lines)
    return "\\left(\n" + inner + "\n  \\right)"


def expr_to_latex(expr, terms_per_line: int = 4) -> str:
    """
    Convert a sympy expression to a LaTeX string using \\begin{equation} +
    \\begin{split}, placing at most `terms_per_line` summands per line.

    Works for both sums and products of sums.

    Parameters
    ----------
    expr           : sympy expression
    terms_per_line : number of summands per line (default 4)

    Returns
    -------
    str  -- ready-to-paste LaTeX source
    """
    top_terms = expr.as_ordered_terms()

    # Case 1: plain sum (or single non-product term)
    if len(top_terms) > 1:
        tokens = _terms_to_tokens(top_terms)
        lines = []
        for i in range(0, len(tokens), terms_per_line):
            chunk = tokens[i : i + terms_per_line]
            lines.append(r"  &" + " ".join(chunk))
        body = " \\\\\n".join(lines)

    # Case 2: product -- render each factor with internal line breaks
    else:
        factors = expr.as_ordered_factors()
        rendered_factors = [_factor_to_latex(f, terms_per_line) for f in factors]
        lines = []
        for i, rf in enumerate(rendered_factors):
            prefix = r"  &" if i == 0 else r"  &\cdot "
            lines.append(prefix + rf)
        body = " \\\\\n".join(lines)

    print(
        r"\begin{equation}" + "\n"
        r"\begin{split}" + "\n"
        + "F_{} =" + body + "\n"
        r"\end{split}" + "\n"
        r"\end{equation}"
    )


from scipy.spatial import ConvexHull
import numpy as np

def newton_polytope_tikz(F, vars, framing=0, scaling=1.0):
    F_framed = F.subs(x, x*y**(framing))
    expr = sp.expand(F_framed)

    points = []

    # Extract all exponent tuples
    for term in expr.as_ordered_terms():
        powers = [term.as_coeff_exponent(var)[1] if term.has(var) else 0 for var in vars]
        points.append(powers)

    # Remove duplicates and convert to numpy array
    points = np.array(sorted(set(tuple(p) for p in points)))

    # Compute convex hull
    hull = ConvexHull(points)
    hull_points = points[hull.vertices]  # vertices are in order around hull

    # Build TikZ points string
    points_str = ', '.join(f"{int(x)}/{int(y)}" for x, y in points)

    # Build hull edges string
    edges_str = ' -- '.join(f"({int(x)},{int(y)})" for x, y in hull_points)
    edges_str += f" -- ({int(hull_points[0][0])},{int(hull_points[0][1])})"  # close the polygon

    tikz_code = f"""\\begin{{center}}
\\begin{{tikzpicture}}[scale={scaling:.1f}]
    \\foreach \\x/\\y in {{{points_str}}} {{
        \\fill (\\x,\\y) circle (2pt);
    }}
    \\draw[very thick, red] {edges_str};
\\end{{tikzpicture}}
\\end{{center}}"""

    print(tikz_code)

